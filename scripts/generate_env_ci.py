#!/usr/bin/env python3
"""Generate .env.ci from .env: same keys, dummy/mock values only.

.env (gitignored, real dev secrets) is the source of truth for which env vars/Airflow
Variables the DAGs need. .env.ci mirrors its keys with harmless placeholder values and is
committed to git -- pr-checks.yml copies it to .env before running `astro dev parse` /
`astro dev pytest`, which the Astro CLI auto-loads, so CI can import every DAG without any
real credentials.

Run this again whenever a new key is added to .env (e.g. a new DAG needs a new credential)
and commit the refreshed .env.ci:

    python scripts/generate_env_ci.py
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENV_PATH = ROOT / ".env"
ENV_CI_PATH = ROOT / ".env.ci"

# Keys whose value must parse as something specific rather than an opaque string, because
# the code reading them expects that shape (e.g. Variable.get(..., deserialize_json=True)).
OVERRIDES = {}


def dummy_value_for(key: str) -> str:
    return OVERRIDES.get(key, f"ci-mock-{key.lower()}")


def main() -> None:
    if not ENV_PATH.exists():
        raise SystemExit(
            f"{ENV_PATH} not found -- pull it first with "
            "`astro env variable export --include-secrets > .env` (see README Setup)."
        )

    keys = []
    for line in ENV_PATH.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key = line.split("=", 1)[0].strip()
        if key:
            keys.append(key)

    header = [
        "# Auto-generated by scripts/generate_env_ci.py -- DO NOT EDIT BY HAND.",
        "# Same keys as .env, dummy/mock values only. Safe to commit -- no real secrets.",
        "# Regenerate after adding a new key to .env: python scripts/generate_env_ci.py",
        "",
    ]
    body = [f"{key}={dummy_value_for(key)}" for key in keys]

    ENV_CI_PATH.write_text("\n".join(header + body) + "\n")
    print(f"Wrote {len(keys)} keys to {ENV_CI_PATH}")


if __name__ == "__main__":
    main()
