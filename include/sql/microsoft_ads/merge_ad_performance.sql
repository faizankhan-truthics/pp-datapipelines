-- include/sql/microsoft_ads/merge_ad_performance.sql
-- Bronze upsert for Microsoft Ads AdPerformanceReportRequest.
-- Staging carries the Release Avro columns (ELT metadata + aggregation_type +
-- raw_data JSON text, one row per CSV row). Grain: account_id x campaign_id x
-- ad_group_id x ad_id x time_period -- one level deeper than ad_group_performance,
-- since ads live under ad groups. time_period is kept exactly as Microsoft returns it
-- (deliberately not parsed/split) -- for Daily it's "yyyy-mm-dd"; for Hourly
-- (FormatVersion 2.0, see build_report_request) it's "yyyy-mm-dd|hour".
-- aggregation_type disambiguates which shape a given row's time_period is in.
-- Re-pulled every run across a trailing lookback window (see
-- microsoft_ads_settings.resolve_window) to catch Microsoft's own retroactive
-- corrections -- QUALIFY dedupes to the latest-seen row per key within this batch,
-- and the MERGE overwrites whatever changed.
--
-- Column set mirrors AD_PERFORMANCE_COLUMNS in dags/microsoft_ads/
-- ad_performance_pipeline.py -- the two must be kept in sync manually (see that
-- file's comments for why certain columns are excluded: Hourly-incompatible columns,
-- grouping-dimension attributes that would split one ad/time_period row into many, and
-- deprecated columns that permanently return zero/empty).
--
-- Ctr/ConversionRate/AllConversionRate come back from Microsoft's CSV with a literal
-- "%" suffix (e.g. "12.50%") -- SAFE_CAST alone silently turns these into NULL instead
-- of erroring, so REPLACE(..., '%', '') strips it first. Learned the hard way on
-- ad_group_performance (confirmed via real data: those columns were 100% NULL before
-- the fix); applied upfront here instead of waiting for a review comment to catch it
-- again. No Ptr on this report (no call-extension metrics at ad level), so only these
-- 3 need it. VideoCompletionRate/ViewThroughRate were confirmed NOT affected on
-- ad_group_performance despite also being "Rate"-named -- not blanket-applying this to
-- every percent-shaped column without checking.

