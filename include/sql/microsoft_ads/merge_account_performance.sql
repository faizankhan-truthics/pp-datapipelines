-- include/sql/microsoft_ads/merge_account_performance.sql
-- Bronze upsert for Microsoft Ads AccountPerformanceReportRequest.
-- Staging carries the Release Avro columns (ELT metadata + aggregation_type +
-- raw_data JSON text, one row per CSV row). Grain: account_id x time_period --
-- simpler than campaign_performance's grain, since AccountReportScope has no campaign
-- dimension at all. time_period is kept exactly as Microsoft returns it (deliberately
-- not parsed/split) -- for Daily it's "yyyy-mm-dd"; for Hourly (FormatVersion 2.0, see
-- build_report_request) it's "yyyy-mm-dd|hour". aggregation_type disambiguates which
-- shape a given row's time_period is in. Re-pulled every run across a trailing lookback
-- window (see microsoft_ads_settings.resolve_window) to catch Microsoft's own
-- retroactive corrections -- QUALIFY dedupes to the latest-seen row per key within this
-- batch, and the MERGE overwrites whatever changed.
--
-- Column set mirrors ACCOUNT_PERFORMANCE_COLUMNS in dags/microsoft_ads/
-- account_performance_pipeline.py -- the two must be kept in sync manually (see that
-- file's comments for why certain columns are excluded: Hourly-incompatible
-- impression-share/click-share/rank-share columns, grouping-dimension attributes that
-- would split one account/time_period row into many, and deprecated columns that
-- permanently return zero/empty).

