-- include/sql/microsoft_ads/merge_ad_group_performance.sql
-- Bronze upsert for Microsoft Ads AdGroupPerformanceReportRequest.
-- Staging carries the Release Avro columns (ELT metadata + aggregation_type +
-- raw_data JSON text, one row per CSV row). Grain: account_id x campaign_id x
-- ad_group_id x time_period -- one level deeper than campaign_performance, since ad
-- groups live under campaigns. time_period is kept exactly as Microsoft returns it
-- (deliberately not parsed/split) -- for Daily it's "yyyy-mm-dd"; for Hourly
-- (FormatVersion 2.0, see build_report_request) it's "yyyy-mm-dd|hour".
-- aggregation_type disambiguates which shape a given row's time_period is in.
-- Re-pulled every run across a trailing lookback window (see
-- microsoft_ads_settings.resolve_window) to catch Microsoft's own retroactive
-- corrections -- QUALIFY dedupes to the latest-seen row per key within this batch,
-- and the MERGE overwrites whatever changed.
--
-- Ctr/ConversionRate/AllConversionRate/Ptr come back from Microsoft's CSV with a
-- literal "%" suffix (e.g. "12.50%") -- SAFE_CAST alone silently turns these into NULL
-- instead of erroring, so REPLACE(..., '%', '') strips it first. Confirmed empirically
-- against real bronze data (100% NULL before the fix); VideoCompletionRate and
-- ViewThroughRate were checked too and do NOT have this issue despite also being
-- "Rate" columns, so don't blanket-apply this to every percent-shaped column without
-- checking first. The same bug exists in campaign_performance/account_performance
-- (already shipped, not yet fixed as of this endpoint's PR -- separate follow-up).
--
-- Column set mirrors AD_GROUP_PERFORMANCE_COLUMNS in dags/microsoft_ads/
-- ad_group_performance_pipeline.py -- the two must be kept in sync manually (see that
-- file's comments for why certain columns are excluded: Hourly-incompatible columns,
-- grouping-dimension attributes that would split one ad_group/time_period row into
-- many, and deprecated columns that permanently return zero/empty).

