-- include/sql/microsoft_ads/merge_campaign_performance.sql
-- Bronze upsert for Microsoft Ads CampaignPerformanceReportRequest.
-- Staging carries the Release Avro columns (ELT metadata + aggregation_type +
-- raw_data JSON text, one row per CSV row). Grain: account_id x campaign_id x
-- time_period. time_period is kept exactly as Microsoft returns it (deliberately not
-- parsed/split) -- for Daily it's "yyyy-mm-dd"; for Hourly (FormatVersion 2.0, see
-- build_report_request) it's "yyyy-mm-dd|hour". aggregation_type disambiguates which
-- shape a given row's time_period is in. Re-pulled every run across a trailing lookback
-- window (see microsoft_ads_settings.resolve_window) to catch Microsoft's own
-- retroactive corrections -- QUALIFY dedupes to the latest-seen row per key within this
-- batch, and the MERGE overwrites whatever changed.
--
-- Column set mirrors CAMPAIGN_PERFORMANCE_COLUMNS in dags/microsoft_ads/
-- campaign_performance_pipeline.py -- the two must be kept in sync manually (see that
-- file's comments for why certain columns are deliberately excluded: impression-share/
-- click-share/rank-share columns incompatible with Hourly aggregation, Historical*
-- columns that are Daily-only, and deprecated columns superseded by their *Qualified
-- replacements).

